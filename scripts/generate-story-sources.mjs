import ts from 'typescript';
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';

// Extract the actual selected demo rather than documenting the gallery wrapper.
const examples = {};
const identifiers = (node) => {
  const names = new Set();
  const visit = (child) => {
    if (ts.isIdentifier(child)) names.add(child.text);
    ts.forEachChild(child, visit);
  };
  visit(node);
  return names;
};
for (const file of readdirSync('src/stories').filter(name => name.endsWith('.stories.tsx'))) {
  const story = readFileSync(`src/stories/${file}`, 'utf8');
  const title = story.match(/title:\s*["']([^"']+)["']/)?.[1];
  const demo = story.match(/<DemoFilter title=["']([^"']+)["']>\s*<(\w+)/);
  const module = story.match(/from ["']@\/components\/showcase\/([^"']+)["']/)?.[1];
  if (!title || !demo || !module) continue;
  const path = `src/components/showcase/${module}.tsx`;
  const source = readFileSync(path, 'utf8');
  const ast = ts.createSourceFile(path, source, ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX);
  const component = ast.statements.find(node => ts.isFunctionDeclaration(node) && node.name?.text === demo[2]);
  if (!component?.body) throw new Error(`Missing demo function: ${title}`);
  let card;
  const visit = node => {
    if (ts.isJsxElement(node) && node.openingElement.tagName.getText(ast) === 'DemoCard') {
      const attr = node.openingElement.attributes.properties.find(attr => ts.isJsxAttribute(attr) && attr.name.getText(ast) === 'title');
      if (attr?.initializer && ts.isStringLiteral(attr.initializer) && attr.initializer.text === demo[1]) card = node;
    }
    ts.forEachChild(node, visit);
  };
  visit(component);
  if (!card) throw new Error(`Missing demo card: ${title}`);
  const locals = component.body.statements.filter(node => !ts.isReturnStatement(node));
  const used = identifiers(card);
  const selectedLocals = new Set();
  let localChanged = true;
  while (localChanged) {
    localChanged = false;
    for (const node of locals) {
      const names = ts.isVariableStatement(node) ? node.declarationList.declarations.flatMap(d => [...identifiers(d.name)]) : node.name ? [node.name.getText(ast)] : [];
      if (selectedLocals.has(node) || !names.some(name => used.has(name))) continue;
      selectedLocals.add(node);
      for (const name of identifiers(node)) used.add(name);
      localChanged = true;
    }
  }
  const setup = locals.filter(node => selectedLocals.has(node));
  const globals = ast.statements.filter(node => !ts.isImportDeclaration(node) && !ts.isFunctionDeclaration(node) && !ts.isExportDeclaration(node));
  const dependencies = [];
  let changed = true;
  while (changed) {
    changed = false;
    for (const node of globals) {
      if (dependencies.includes(node)) continue;
      const names = ts.isVariableStatement(node) ? node.declarationList.declarations.map(d => d.name.getText(ast)) : node.name ? [node.name.getText(ast)] : [];
      if (!names.some(name => used.has(name))) continue;
      dependencies.push(node);
      for (const name of identifiers(node)) used.add(name);
      changed = true;
    }
  }
  const imports = ast.statements.filter(ts.isImportDeclaration).flatMap(node => {
    const clause = node.importClause;
    if (!clause) return [node.getText(ast)];
    const parts = [];
    if (clause.name && used.has(clause.name.text)) parts.push(clause.name.getText(ast));
    if (clause.namedBindings && ts.isNamespaceImport(clause.namedBindings) && used.has(clause.namedBindings.name.text)) parts.push(clause.namedBindings.getText(ast));
    if (clause.namedBindings && ts.isNamedImports(clause.namedBindings)) {
      const bindings = clause.namedBindings.elements.filter(binding => used.has(binding.name.text));
      if (bindings.length) parts.push(`{ ${bindings.map(binding => binding.getText(ast)).join(', ')} }`);
    }
    return parts.length ? [`import ${clause.isTypeOnly ? 'type ' : ''}${parts.join(', ')} from ${(node.moduleSpecifier.text.startsWith('./') ? JSON.stringify('@/components/showcase/' + node.moduleSpecifier.text.slice(2)) : node.moduleSpecifier.getText(ast))};`] : [];
  });
  const code = `${imports.join('\n')}\n\n${dependencies.map(node => node.getText(ast)).join('\n')}\n\nexport function Example() {\n${setup.map(node => node.getText(ast)).join('\n')}\nreturn (\n${card.getText(ast)}\n);\n}\n`;
  const parsed = ts.createSourceFile('example.tsx', code, ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX);
  if (parsed.parseDiagnostics.length) throw new Error(`Invalid extracted example: ${title}`);
  examples[title] = ts.createPrinter({ newLine: ts.NewLineKind.LineFeed }).printFile(parsed);
}
writeFileSync('.storybook/generated-examples.ts', `// Generated by scripts/generate-story-sources.mjs. Edit the showcase demos instead.\nexport const examples: Record<string, string> = ${JSON.stringify(examples, null, 2)};\n`);
console.log(`Prepared ${Object.keys(examples).length} composition source examples.`);
